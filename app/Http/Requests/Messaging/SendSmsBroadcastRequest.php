<?php

declare(strict_types=1);

namespace App\Http\Requests\Messaging;

use App\Enums\MessageChannel;
use App\Models\Message;
use App\Models\User;
use App\Sms\BroadcastAudience;
use App\Sms\Templates;
use App\Support\Tenancy\TenantContext;
use Illuminate\Foundation\Http\FormRequest;
use Illuminate\Validation\Rule;

/** POST /app/messages/send: the composer's audience, text and idempotency key (settings.manage). */
final class SendSmsBroadcastRequest extends FormRequest
{
    public function authorize(): bool
    {
        $user = $this->user();

        return $user instanceof User && $user->can('send', Message::class);
    }

    /** @return array<string, array<int, mixed>> */
    public function rules(): array
    {
        $tenantId = app(TenantContext::class)->tenantId();

        return [
            'channel' => ['nullable', Rule::enum(MessageChannel::class)],
            'target' => ['required', Rule::in(BroadcastAudience::TARGETS)],
            'customer' => ['nullable', 'required_if:target,customer', 'uuid', Rule::exists('customers', 'uuid')->where('tenant_id', $tenantId)->whereNull('deleted_at')],
            'group_id' => ['nullable', 'required_if:target,group', 'integer', Rule::exists('customer_groups', 'id')->where('tenant_id', $tenantId)->whereNull('deleted_at')],
            'body' => ['required', 'string', 'max:'.BroadcastAudience::MAX_BODY],
            'template' => ['nullable', 'string', Rule::in(Templates::keys())],
            // Generated by the composer when it opens (and again after each send); a repeat returns the same broadcast.
            'idempotency_key' => ['required', 'string', 'min:16', 'max:64', 'regex:/^[A-Za-z0-9-]+$/'],
        ];
    }
}
