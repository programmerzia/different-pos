import { useState, type FormEvent, type KeyboardEvent } from 'react';
import { FormField } from '@/components/form-field';
import { MoneyInput } from '@/components/money-input';
import { NativeSelect } from '@/components/native-select';
import type { ScanProduct } from '@/components/scan-field';
import { Button } from '@/components/ui/button';
import {
    Dialog,
    DialogContent,
    DialogDescription,
    DialogFooter,
    DialogHeader,
    DialogTitle,
} from '@/components/ui/dialog';
import { Input } from '@/components/ui/input';
import { useHotkeyScope } from '@/hotkeys/use-hotkeys';
import { useT } from '@/i18n';
import { ApiError, apiRequest } from '@/lib/api';

export type UnitOption = {
    id: number;
    name: string;
    short_name: string;
    allows_decimal: boolean;
};

type ItemType = 'raw_material' | 'finished';

/**
 * The GRN's inline "New item": a product or raw material created over JSON (`purchases.items.store`)
 * without leaving the bill. The SKU is generated by the server; the new item comes back as a lookup row.
 */
export function NewItemDialog({
    open,
    onOpenChange,
    units,
    initialName,
    onCreated,
}: {
    open: boolean;
    onOpenChange: (open: boolean) => void;
    units: UnitOption[];
    /** What the buyer had typed in the search box. */
    initialName: string;
    /** The created item; `cost_price` is what was typed here, even for a user who may not see costs. */
    onCreated: (item: ScanProduct) => void;
}) {
    const { t } = useT();
    useHotkeyScope('dialog', open);
    const [name, setName] = useState(initialName);
    const [itemType, setItemType] = useState<ItemType>('raw_material');
    const [unitId, setUnitId] = useState<string>(
        units[0] ? String(units[0].id) : '',
    );
    const [cost, setCost] = useState<number | null>(null);
    const [price, setPrice] = useState<number | null>(null);
    const [errors, setErrors] = useState<Record<string, string>>({});
    const [busy, setBusy] = useState(false);

    const submit = async (event?: FormEvent) => {
        event?.preventDefault();
        event?.stopPropagation();
        if (busy) {
            return;
        }
        const found: Record<string, string> = {};
        if (name.trim() === '') {
            found['name'] = t('purchases.err_item_name');
        }
        if (unitId === '') {
            found['unit_id'] = t('products.err_unit');
        }
        if (itemType === 'finished' && price === null) {
            found['sale_price'] = t('products.err_price');
        }
        setErrors(found);
        if (Object.keys(found).length > 0) {
            return;
        }
        setBusy(true);
        try {
            const item = await apiRequest<ScanProduct>('/app/purchases/items', {
                method: 'POST',
                body: {
                    name: name.trim(),
                    item_type: itemType,
                    unit_id: Number(unitId),
                    cost_price: cost ?? 0,
                    ...(itemType === 'finished' ? { sale_price: price } : {}),
                },
            });
            onCreated({ ...item, cost_price: cost ?? item.cost_price });
            onOpenChange(false);
        } catch (e) {
            setErrors(
                e instanceof ApiError && Object.keys(e.fieldErrors).length > 0
                    ? e.fieldErrors
                    : {
                          form:
                              e instanceof ApiError && e.detail
                                  ? e.detail
                                  : t('purchases.new_item_failed'),
                      },
            );
        } finally {
            setBusy(false);
        }
    };

    // Ctrl+Enter saves this dialog; the page's own Ctrl+Enter (receive) must not also fire.
    const onKeyDown = (event: KeyboardEvent) => {
        if (event.key === 'Enter') {
            event.nativeEvent.stopPropagation();
            if (event.ctrlKey || event.metaKey) {
                event.preventDefault();
                void submit();
            }
        }
    };

    return (
        <Dialog open={open} onOpenChange={onOpenChange}>
            <DialogContent className="max-w-120" onKeyDown={onKeyDown}>
                <form noValidate onSubmit={(e) => void submit(e)}>
                    <DialogHeader>
                        <DialogTitle>
                            {t('purchases.new_item_title')}
                        </DialogTitle>
                        <DialogDescription>
                            {t('purchases.new_item_hint')}
                        </DialogDescription>
                    </DialogHeader>
                    <div className="my-4 grid gap-3">
                        {errors['form'] ? (
                            <p
                                role="alert"
                                className="rounded-lg bg-danger-soft p-2.5 text-sm font-semibold text-destructive"
                            >
                                {errors['form']}
                            </p>
                        ) : null}
                        <FormField
                            label={`${t('products.name_en')} *`}
                            error={errors['name']}
                        >
                            <Input
                                className="min-h-11"
                                value={name}
                                autoComplete="off"
                                maxLength={190}
                                autoFocus
                                onChange={(e) => setName(e.target.value)}
                            />
                        </FormField>
                        <div className="grid grid-cols-2 gap-3">
                            <FormField
                                label={t('products.item_type')}
                                error={errors['item_type']}
                            >
                                <NativeSelect
                                    value={itemType}
                                    onChange={(e) =>
                                        setItemType(e.target.value as ItemType)
                                    }
                                >
                                    <option value="raw_material">
                                        {t('products.item_raw_material')}
                                    </option>
                                    <option value="finished">
                                        {t('products.item_finished')}
                                    </option>
                                </NativeSelect>
                            </FormField>
                            <FormField
                                label={`${t('products.unit_label')} *`}
                                error={errors['unit_id']}
                                hint={
                                    itemType === 'raw_material'
                                        ? t('products.raw_unit_hint')
                                        : undefined
                                }
                            >
                                <NativeSelect
                                    value={unitId}
                                    onChange={(e) => setUnitId(e.target.value)}
                                >
                                    {units.map((u) => (
                                        <option key={u.id} value={u.id}>
                                            {u.name} ({u.short_name})
                                        </option>
                                    ))}
                                </NativeSelect>
                            </FormField>
                        </div>
                        <div className="grid grid-cols-2 gap-3">
                            <FormField
                                label={t('products.raw_cost_label')}
                                error={errors['cost_price']}
                            >
                                <MoneyInput
                                    className="min-h-11 text-right font-bold"
                                    value={cost}
                                    onChange={setCost}
                                />
                            </FormField>
                            {itemType === 'finished' ? (
                                <FormField
                                    label={`${t('products.mrp_label')} *`}
                                    error={errors['sale_price']}
                                >
                                    <MoneyInput
                                        className="min-h-11 text-right font-bold"
                                        value={price}
                                        onChange={setPrice}
                                    />
                                </FormField>
                            ) : null}
                        </div>
                    </div>
                    <DialogFooter>
                        <Button
                            type="button"
                            variant="outline"
                            className="min-h-11"
                            onClick={() => onOpenChange(false)}
                        >
                            {t('common.cancel')}
                        </Button>
                        <Button
                            type="submit"
                            className="min-h-11"
                            disabled={busy}
                        >
                            {t('purchases.new_item_add')}
                        </Button>
                    </DialogFooter>
                </form>
            </DialogContent>
        </Dialog>
    );
}
